package oodschema

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strings"
)

const generatedHeader = "-- Code generated by cmd/ood-schema-render from the canonical OOD Graph protocol; DO NOT EDIT."

var (
	createTablePattern = regexp.MustCompile(`(?is)^CREATE\s+TABLE\s+([A-Za-z][A-Za-z0-9_]*)\s*\(`)
	primaryKeyPattern  = regexp.MustCompile(`(?is)\)\s+PRIMARY\s+KEY\s*\(([^)]*)\)\s*$`)
	createIndexPattern = regexp.MustCompile(`(?is)^CREATE\s+(?:(?:UNIQUE|NULL_FILTERED)\s+)*(?:SEARCH\s+|VECTOR\s+)?INDEX\s+([A-Za-z][A-Za-z0-9_]*)\s+ON\s+([A-Za-z][A-Za-z0-9_]*)\s*\(`)
)

type document struct {
	DocID    string          `json:"doc_id"`
	Title    string          `json:"title"`
	Version  json.RawMessage `json:"version"`
	Sections struct {
		Storage storageSection `json:"s6_spanner_storage_model"`
		Graph   graphSection   `json:"s7_spanner_property_graph_schema"`
	} `json:"sections"`
}

type graphSection struct {
	Model propertyGraphModel `json:"create_property_graph_model"`
}

type propertyGraphModel struct {
	Normative        bool   `json:"ddl_is_normative_schema_shape"`
	ApplyInstruction bool   `json:"ddl_apply_instruction"`
	Name             string `json:"property_graph_name"`
	NodeTables       string `json:"node_tables"`
	EdgeTables       string `json:"edge_tables_generation"`
}

type storageSection struct {
	TableSurfaces map[string]json.RawMessage `json:"table_surfaces"`
	DDL           ddlModel                   `json:"spanner_ddl_model"`
}

type ddlModel struct {
	Normative        bool             `json:"ddl_is_normative_schema_shape"`
	ApplyInstruction bool             `json:"ddl_apply_instruction"`
	Parity           tableParityModel `json:"table_surface_column_order_parity"`
	Statements       []string         `json:"statements"`
}

type tableParityModel struct {
	Required bool `json:"required"`
}

type tableSurface struct {
	PhysicalTableName string          `json:"physical_table_name"`
	PrimaryKey        []string        `json:"primary_key"`
	Columns           json.RawMessage `json:"columns"`
}

type orderedColumn struct {
	Name       string
	Definition string
}

type parsedTable struct {
	Name       string
	Columns    []orderedColumn
	PrimaryKey []string
}

type Receipt struct {
	ReceiptKind                 string   `json:"receipt_kind"`
	ReceiptVersion              string   `json:"receipt_version"`
	Result                      string   `json:"result"`
	OODDocID                    string   `json:"ood_doc_id"`
	OODVersion                  string   `json:"ood_version"`
	OODSpecSHA256               string   `json:"ood_spec_sha256"`
	RenderedDDLSHA256           string   `json:"rendered_ddl_sha256"`
	StorageDDLStatementCount    int      `json:"storage_ddl_statement_count"`
	TableSurfaceCount           int      `json:"table_surface_count"`
	DDLStatementCount           int      `json:"ddl_statement_count"`
	PropertyGraphStatementCount int      `json:"property_graph_statement_count"`
	CreateTableCount            int      `json:"create_table_count"`
	CreateIndexCount            int      `json:"create_index_count"`
	ColumnParityTableCount      int      `json:"column_parity_table_count"`
	DDLApplyAuthorized          bool     `json:"ddl_apply_authorized"`
	DDLApplyRule                string   `json:"ddl_apply_rule"`
	PhysicalTableNames          []string `json:"physical_table_names"`
}

func Render(oodBytes []byte) ([]byte, Receipt, error) {
	if err := rejectDuplicateJSONKeys(oodBytes); err != nil {
		return nil, Receipt{}, err
	}
	var doc document
	decoder := json.NewDecoder(bytes.NewReader(oodBytes))
	if err := decoder.Decode(&doc); err != nil {
		return nil, Receipt{}, fmt.Errorf("decode OOD document: %w", err)
	}
	version, err := scalarString(doc.Version)
	if err != nil {
		return nil, Receipt{}, fmt.Errorf("OOD version: %w", err)
	}
	if doc.DocID == "" || version == "" {
		return nil, Receipt{}, errors.New("OOD doc_id and version are required")
	}
	if !doc.Sections.Storage.DDL.Normative {
		return nil, Receipt{}, errors.New("s6 spanner DDL is not marked as the normative schema shape")
	}
	if doc.Sections.Storage.DDL.ApplyInstruction {
		return nil, Receipt{}, errors.New("s6 ddl_apply_instruction must remain false; rendering is not deployment authorization")
	}
	if !doc.Sections.Storage.DDL.Parity.Required {
		return nil, Receipt{}, errors.New("s6 table/DDL column-order parity is not required")
	}
	if len(doc.Sections.Storage.TableSurfaces) == 0 || len(doc.Sections.Storage.DDL.Statements) == 0 {
		return nil, Receipt{}, errors.New("s6 table surfaces and DDL statements must be non-empty")
	}
	if !doc.Sections.Graph.Model.Normative || doc.Sections.Graph.Model.ApplyInstruction {
		return nil, Receipt{}, errors.New("s7 property-graph DDL must be normative and non-authorizing")
	}

	parsedTables := make(map[string]parsedTable)
	indexNames := make(map[string]struct{})
	indexTables := make(map[string]string)
	for i, statement := range doc.Sections.Storage.DDL.Statements {
		statement = strings.TrimSpace(statement)
		if statement == "" {
			return nil, Receipt{}, fmt.Errorf("DDL statement[%d] is empty", i)
		}
		if strings.HasSuffix(statement, ";") {
			return nil, Receipt{}, fmt.Errorf("DDL statement[%d] carries a semicolon; renderer owns statement delimiters", i)
		}
		if match := createTablePattern.FindStringSubmatch(statement); len(match) != 0 {
			table, err := parseCreateTable(statement)
			if err != nil {
				return nil, Receipt{}, fmt.Errorf("DDL statement[%d]: %w", i, err)
			}
			if _, duplicate := parsedTables[table.Name]; duplicate {
				return nil, Receipt{}, fmt.Errorf("duplicate CREATE TABLE for %s", table.Name)
			}
			parsedTables[table.Name] = table
			continue
		}
		if match := createIndexPattern.FindStringSubmatch(statement); len(match) != 0 {
			if _, duplicate := indexNames[match[1]]; duplicate {
				return nil, Receipt{}, fmt.Errorf("duplicate CREATE INDEX for %s", match[1])
			}
			indexNames[match[1]] = struct{}{}
			indexTables[match[1]] = match[2]
			continue
		}
		return nil, Receipt{}, fmt.Errorf("DDL statement[%d] is neither a supported CREATE TABLE nor CREATE INDEX statement", i)
	}

	physicalNames := make([]string, 0, len(doc.Sections.Storage.TableSurfaces))
	seenPhysicalNames := make(map[string]string)
	for logicalName, rawSurface := range doc.Sections.Storage.TableSurfaces {
		var surface tableSurface
		if err := json.Unmarshal(rawSurface, &surface); err != nil {
			return nil, Receipt{}, fmt.Errorf("decode table surface %s: %w", logicalName, err)
		}
		if surface.PhysicalTableName == "" || len(surface.PrimaryKey) == 0 || len(surface.Columns) == 0 {
			return nil, Receipt{}, fmt.Errorf("table surface %s lacks physical_table_name, primary_key, or columns", logicalName)
		}
		if prior, duplicate := seenPhysicalNames[surface.PhysicalTableName]; duplicate {
			return nil, Receipt{}, fmt.Errorf("table surfaces %s and %s both own %s", prior, logicalName, surface.PhysicalTableName)
		}
		seenPhysicalNames[surface.PhysicalTableName] = logicalName
		physicalNames = append(physicalNames, surface.PhysicalTableName)
		ddlTable, found := parsedTables[surface.PhysicalTableName]
		if !found {
			return nil, Receipt{}, fmt.Errorf("table surface %s has no CREATE TABLE for %s", logicalName, surface.PhysicalTableName)
		}
		columns, err := decodeOrderedStringObject(surface.Columns)
		if err != nil {
			return nil, Receipt{}, fmt.Errorf("table surface %s columns: %w", logicalName, err)
		}
		if err := compareColumns(logicalName, columns, ddlTable.Columns); err != nil {
			return nil, Receipt{}, err
		}
		if !equalStrings(surface.PrimaryKey, ddlTable.PrimaryKey) {
			return nil, Receipt{}, fmt.Errorf("table surface %s primary key mismatch: structured=%v ddl=%v", logicalName, surface.PrimaryKey, ddlTable.PrimaryKey)
		}
	}
	if len(parsedTables) != len(seenPhysicalNames) {
		extra := make([]string, 0)
		for name := range parsedTables {
			if _, found := seenPhysicalNames[name]; !found {
				extra = append(extra, name)
			}
		}
		sort.Strings(extra)
		return nil, Receipt{}, fmt.Errorf("CREATE TABLE statements absent from table_surfaces: %v", extra)
	}
	for indexName, tableName := range indexTables {
		if _, found := parsedTables[tableName]; !found {
			return nil, Receipt{}, fmt.Errorf("index %s references unknown table %s", indexName, tableName)
		}
	}
	sort.Strings(physicalNames)
	propertyGraphStatement, err := renderPropertyGraph(doc.Sections.Graph.Model, parsedTables)
	if err != nil {
		return nil, Receipt{}, err
	}

	oodDigest := sha256.Sum256(oodBytes)
	header := fmt.Sprintf("%s\n-- OOD doc_id: %s\n-- OOD version: %s\n-- OOD spec SHA-256: %s\n-- Rendering is not DDL-apply authorization; the sanctioned deployment gate remains mandatory.\n\n",
		generatedHeader, doc.DocID, version, hex.EncodeToString(oodDigest[:]))
	var rendered strings.Builder
	rendered.WriteString(header)
	for i, statement := range doc.Sections.Storage.DDL.Statements {
		if i != 0 {
			rendered.WriteString("\n\n")
		}
		rendered.WriteString(strings.TrimSpace(statement))
		rendered.WriteString(";")
	}
	rendered.WriteString("\n\n")
	rendered.WriteString(propertyGraphStatement)
	rendered.WriteString(";")
	rendered.WriteString("\n")
	ddlBytes := []byte(rendered.String())
	ddlDigest := sha256.Sum256(ddlBytes)
	receipt := Receipt{
		ReceiptKind:                 "ood_graph_spanner_schema_render_receipt",
		ReceiptVersion:              "1",
		Result:                      "pass",
		OODDocID:                    doc.DocID,
		OODVersion:                  version,
		OODSpecSHA256:               hex.EncodeToString(oodDigest[:]),
		RenderedDDLSHA256:           hex.EncodeToString(ddlDigest[:]),
		StorageDDLStatementCount:    len(doc.Sections.Storage.DDL.Statements),
		TableSurfaceCount:           len(doc.Sections.Storage.TableSurfaces),
		DDLStatementCount:           len(doc.Sections.Storage.DDL.Statements) + 1,
		PropertyGraphStatementCount: 1,
		CreateTableCount:            len(parsedTables),
		CreateIndexCount:            len(indexNames),
		ColumnParityTableCount:      len(parsedTables),
		DDLApplyAuthorized:          false,
		DDLApplyRule:                "render_and_verify_only;apply_requires_the_separate_sanctioned_ddl_gate",
		PhysicalTableNames:          physicalNames,
	}
	return ddlBytes, receipt, nil
}

func VerifyRendered(ddl []byte, receipt Receipt) error {
	digest := sha256.Sum256(ddl)
	if receipt.Result != "pass" || receipt.DDLApplyAuthorized {
		return errors.New("render receipt must be a non-authorizing pass")
	}
	if hex.EncodeToString(digest[:]) != receipt.RenderedDDLSHA256 {
		return errors.New("rendered DDL SHA-256 does not match its receipt")
	}
	headerHash := "-- OOD spec SHA-256: " + receipt.OODSpecSHA256
	if !strings.Contains(string(ddl), headerHash) {
		return errors.New("rendered DDL header does not bind the receipt OOD digest")
	}
	var statementCount, tableCount, indexCount, propertyGraphCount int
	var physicalNames []string
	for _, line := range strings.Split(string(ddl), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "CREATE ") {
			continue
		}
		if !strings.HasSuffix(line, ";") {
			return errors.New("generated DDL statement is not semicolon terminated")
		}
		statement := strings.TrimSuffix(line, ";")
		statementCount++
		if match := createTablePattern.FindStringSubmatch(statement); len(match) != 0 {
			if _, err := parseCreateTable(statement); err != nil {
				return err
			}
			tableCount++
			physicalNames = append(physicalNames, match[1])
			continue
		}
		if createIndexPattern.MatchString(statement) {
			indexCount++
			continue
		}
		if strings.HasPrefix(statement, "CREATE PROPERTY GRAPH ") {
			propertyGraphCount++
			continue
		}
		return fmt.Errorf("unsupported generated DDL statement: %s", line)
	}
	sort.Strings(physicalNames)
	if statementCount != receipt.DDLStatementCount || tableCount != receipt.CreateTableCount || indexCount != receipt.CreateIndexCount || propertyGraphCount != receipt.PropertyGraphStatementCount {
		return fmt.Errorf("generated DDL counts do not match receipt: statements=%d tables=%d indexes=%d property_graphs=%d", statementCount, tableCount, indexCount, propertyGraphCount)
	}
	if !equalStrings(physicalNames, receipt.PhysicalTableNames) {
		return errors.New("generated DDL physical table roster does not match receipt")
	}
	return nil
}

func renderPropertyGraph(model propertyGraphModel, tables map[string]parsedTable) (string, error) {
	if model.Name == "" || strings.TrimSpace(model.NodeTables) == "" || strings.TrimSpace(model.EdgeTables) == "" {
		return "", errors.New("s7 property graph name, node tables, and edge tables are required")
	}
	namePattern := regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*$`)
	if !namePattern.MatchString(model.Name) {
		return "", fmt.Errorf("invalid property graph name %q", model.Name)
	}
	tablePrefix := regexp.MustCompile(`^([A-Za-z][A-Za-z0-9_]*)\s+`)
	nodeMatch := tablePrefix.FindStringSubmatch(strings.TrimSpace(model.NodeTables))
	edgeMatch := tablePrefix.FindStringSubmatch(strings.TrimSpace(model.EdgeTables))
	if len(nodeMatch) == 0 || len(edgeMatch) == 0 {
		return "", errors.New("s7 node or edge table definition lacks a physical table prefix")
	}
	for role, tableName := range map[string]string{"node": nodeMatch[1], "edge": edgeMatch[1]} {
		if _, found := tables[tableName]; !found {
			return "", fmt.Errorf("s7 %s table %s is absent from s6 table surfaces", role, tableName)
		}
	}
	references := regexp.MustCompile(`(?i)\bREFERENCES\s+([A-Za-z][A-Za-z0-9_]*)\s*\(`).FindAllStringSubmatch(model.EdgeTables, -1)
	if len(references) != 2 {
		return "", fmt.Errorf("s7 edge definition has %d endpoint references, want 2", len(references))
	}
	for _, reference := range references {
		if reference[1] != nodeMatch[1] {
			return "", fmt.Errorf("s7 edge endpoint references %s instead of node table %s", reference[1], nodeMatch[1])
		}
	}
	if !strings.Contains(model.NodeTables, "DYNAMIC LABEL") || !strings.Contains(model.EdgeTables, "DYNAMIC LABEL") {
		return "", errors.New("s7 property graph must expose both dynamic label sources")
	}
	return fmt.Sprintf("CREATE PROPERTY GRAPH %s NODE TABLES (%s) EDGE TABLES (%s)", model.Name, strings.TrimSpace(model.NodeTables), strings.TrimSpace(model.EdgeTables)), nil
}

func parseCreateTable(statement string) (parsedTable, error) {
	match := createTablePattern.FindStringSubmatchIndex(statement)
	if len(match) == 0 {
		return parsedTable{}, errors.New("not a CREATE TABLE statement")
	}
	name := statement[match[2]:match[3]]
	open := match[1] - 1
	close, err := matchingParen(statement, open)
	if err != nil {
		return parsedTable{}, fmt.Errorf("CREATE TABLE %s: %w", name, err)
	}
	primaryMatch := primaryKeyPattern.FindStringSubmatch(statement[close:])
	if len(primaryMatch) == 0 {
		return parsedTable{}, fmt.Errorf("CREATE TABLE %s lacks a terminal PRIMARY KEY", name)
	}
	segments, err := splitTopLevel(statement[open+1 : close])
	if err != nil {
		return parsedTable{}, fmt.Errorf("CREATE TABLE %s columns: %w", name, err)
	}
	columns := make([]orderedColumn, 0, len(segments))
	for _, segment := range segments {
		segment = strings.TrimSpace(segment)
		upper := strings.ToUpper(segment)
		if strings.HasPrefix(upper, "CONSTRAINT ") || strings.HasPrefix(upper, "FOREIGN KEY ") || strings.HasPrefix(upper, "CHECK ") || strings.HasPrefix(upper, "PRIMARY KEY ") {
			continue
		}
		field := strings.IndexAny(segment, " \t\r\n")
		if field <= 0 {
			return parsedTable{}, fmt.Errorf("CREATE TABLE %s has malformed column definition %q", name, segment)
		}
		columns = append(columns, orderedColumn{Name: segment[:field], Definition: normalizeDDL(segment[field:])})
	}
	primaryKey := splitCommaList(primaryMatch[1])
	return parsedTable{Name: name, Columns: columns, PrimaryKey: primaryKey}, nil
}

func compareColumns(logicalName string, structured, ddl []orderedColumn) error {
	if len(structured) != len(ddl) {
		return fmt.Errorf("table surface %s column count mismatch: structured=%d ddl=%d", logicalName, len(structured), len(ddl))
	}
	for i := range structured {
		if structured[i].Name != ddl[i].Name || normalizeDDL(structured[i].Definition) != normalizeDDL(ddl[i].Definition) {
			return fmt.Errorf("table surface %s column[%d] mismatch: structured=%s %s ddl=%s %s", logicalName, i,
				structured[i].Name, normalizeDDL(structured[i].Definition), ddl[i].Name, normalizeDDL(ddl[i].Definition))
		}
	}
	return nil
}

func decodeOrderedStringObject(raw []byte) ([]orderedColumn, error) {
	decoder := json.NewDecoder(bytes.NewReader(raw))
	token, err := decoder.Token()
	if err != nil {
		return nil, err
	}
	if delimiter, ok := token.(json.Delim); !ok || delimiter != '{' {
		return nil, errors.New("columns must be an object")
	}
	var columns []orderedColumn
	seen := make(map[string]struct{})
	for decoder.More() {
		keyToken, err := decoder.Token()
		if err != nil {
			return nil, err
		}
		key, ok := keyToken.(string)
		if !ok {
			return nil, errors.New("column name must be a string")
		}
		if _, duplicate := seen[key]; duplicate {
			return nil, fmt.Errorf("duplicate column %q", key)
		}
		seen[key] = struct{}{}
		var definition string
		if err := decoder.Decode(&definition); err != nil {
			return nil, fmt.Errorf("column %s definition: %w", key, err)
		}
		columns = append(columns, orderedColumn{Name: key, Definition: definition})
	}
	if _, err := decoder.Token(); err != nil {
		return nil, err
	}
	return columns, nil
}

func matchingParen(value string, open int) (int, error) {
	depth := 0
	inQuote := byte(0)
	for i := open; i < len(value); i++ {
		c := value[i]
		if inQuote != 0 {
			if c == inQuote {
				if i+1 < len(value) && value[i+1] == inQuote {
					i++
					continue
				}
				inQuote = 0
			}
			continue
		}
		if c == '\'' || c == '"' || c == '`' {
			inQuote = c
			continue
		}
		switch c {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return i, nil
			}
			if depth < 0 {
				return 0, errors.New("unbalanced closing parenthesis")
			}
		}
	}
	return 0, errors.New("unclosed parenthesis")
}

func splitTopLevel(value string) ([]string, error) {
	var result []string
	start, depth := 0, 0
	inQuote := byte(0)
	for i := 0; i < len(value); i++ {
		c := value[i]
		if inQuote != 0 {
			if c == inQuote {
				if i+1 < len(value) && value[i+1] == inQuote {
					i++
					continue
				}
				inQuote = 0
			}
			continue
		}
		if c == '\'' || c == '"' || c == '`' {
			inQuote = c
			continue
		}
		switch c {
		case '(':
			depth++
		case ')':
			depth--
			if depth < 0 {
				return nil, errors.New("unbalanced closing parenthesis")
			}
		case ',':
			if depth == 0 {
				result = append(result, value[start:i])
				start = i + 1
			}
		}
	}
	if inQuote != 0 || depth != 0 {
		return nil, errors.New("unclosed quote or parenthesis")
	}
	result = append(result, value[start:])
	return result, nil
}

func splitCommaList(value string) []string {
	parts := strings.Split(value, ",")
	for i := range parts {
		parts[i] = strings.TrimSpace(parts[i])
	}
	return parts
}

func normalizeDDL(value string) string {
	return strings.Join(strings.Fields(strings.TrimSpace(value)), " ")
}

func equalStrings(left, right []string) bool {
	if len(left) != len(right) {
		return false
	}
	for i := range left {
		if left[i] != right[i] {
			return false
		}
	}
	return true
}

func scalarString(raw json.RawMessage) (string, error) {
	value := strings.TrimSpace(string(raw))
	if value == "" || value == "null" {
		return "", errors.New("required")
	}
	if strings.HasPrefix(value, "\"") {
		var decoded string
		if err := json.Unmarshal(raw, &decoded); err != nil {
			return "", err
		}
		return decoded, nil
	}
	var number json.Number
	decoder := json.NewDecoder(strings.NewReader(value))
	decoder.UseNumber()
	if err := decoder.Decode(&number); err != nil {
		return "", errors.New("must be a string or JSON number")
	}
	return number.String(), nil
}

func rejectDuplicateJSONKeys(data []byte) error {
	decoder := json.NewDecoder(bytes.NewReader(data))
	var walk func(string) error
	walk = func(path string) error {
		token, err := decoder.Token()
		if err != nil {
			return err
		}
		delimiter, isDelimiter := token.(json.Delim)
		if !isDelimiter {
			return nil
		}
		switch delimiter {
		case '{':
			seen := make(map[string]struct{})
			for decoder.More() {
				keyToken, err := decoder.Token()
				if err != nil {
					return err
				}
				key, ok := keyToken.(string)
				if !ok {
					return fmt.Errorf("non-string object key at %s", path)
				}
				if _, duplicate := seen[key]; duplicate {
					return fmt.Errorf("duplicate JSON key at %s.%s", path, key)
				}
				seen[key] = struct{}{}
				if err := walk(path + "." + key); err != nil {
					return err
				}
			}
			_, err = decoder.Token()
			return err
		case '[':
			for i := 0; decoder.More(); i++ {
				if err := walk(fmt.Sprintf("%s[%d]", path, i)); err != nil {
					return err
				}
			}
			_, err = decoder.Token()
			return err
		default:
			return fmt.Errorf("unexpected JSON delimiter %q at %s", delimiter, path)
		}
	}
	if err := walk("$"); err != nil {
		return err
	}
	if _, err := decoder.Token(); !errors.Is(err, io.EOF) {
		if err == nil {
			return errors.New("multiple JSON values")
		}
		return err
	}
	return nil
}
