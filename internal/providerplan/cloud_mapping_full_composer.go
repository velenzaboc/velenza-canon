// CloudMappingNativeResourceIdentity is supplied by the sealed native graph
// context after it has assigned the authoritative candidate API-resource ID.
// The mapping catalog must not manufacture either value.
type CloudMappingNativeResourceIdentity struct {
	APIResourceID           string
	APIResourceSourceSymbol string
	// SchemaOwnerEvidenceLocatorIDs are supplied by the sealed evidence
	// classifier, keyed by source-schema owner symbol. They bind the bridge
	// directly to the owner schema's exact hydrated range.
	SchemaOwnerEvidenceLocatorIDs map[string]string
}

// CloudMappingSourceContractProjection is the complete mapping-owned portion
// of a source-contract artifact. A caller merges it with separately sealed
// source documents, operation facts, and validation summary before invoking
// the existing source-package compiler. This type intentionally cannot create
// those authority-bearing rows itself.
type CloudMappingSourceContractProjection struct {
	FieldContracts         []map[string]interface{}
	ResourceSchemaBindings []map[string]interface{}
}

// CloudMappingSchemaOwnerSelection is the exact declared-schema evidence that
// must be independently classified before a v1 bridge may name its owner.
// It is intentionally source-local; conversion to a sealed evidenceLocator is
// performed by the source-package owner with its manifest coordinates.
type CloudMappingSchemaOwnerSelection struct {
	SourceSchemaOwnerSymbol string
	ModelSourceID           string
	Locator                 CloudCatalogEvidenceLocator
	SelectedRangeSHA256     string
}

// CloudMappingProviderExecution is the reusable output of executing one
// provider partition. The returned facts are inputs to the normal target
// materialization and dependent artifact compiler; they are not qualified
// facts by themselves.
type CloudMappingProviderExecution struct {
	ProviderID            string
	Roster                CloudMappingOccurrenceRoster
	FieldFacts            []exactDocumentationDerivedFact
	SchemaOwnerSelections []CloudMappingSchemaOwnerSelection
	FieldSelections       []CloudMappingFieldSelection
}

// CloudMappingProviderDerivationBundle is the exact profile/execution closure
// a source-package owner needs to materialize the remaining dependent roles.
type CloudMappingProviderDerivationBundle struct {
	Execution        CloudMappingProviderExecution
	ProfileRows      dependencySemanticRows
	Profiles         map[string]executableDocumentationDerivationProfile
	ProfileExecution exactDocumentationDerivationProfileExecutionSet
}

// BuildCloudMappingProviderDerivationBundle constructs validation-bound
// profile rows directly from the retained generated bytes, then executes the
// complete profile set through the normal multi-profile executor. It gives the
// source-package assembler the same facts and page/result roots that Verify
// will later validate.
func BuildCloudMappingProviderDerivationBundle(roster CloudMappingOccurrenceRoster, proof sourceClassificationSelectionProof, bodies map[string]exactEvidenceBody) (CloudMappingProviderDerivationBundle, error) {
	execution, err := ExecuteCloudMappingProviderPrograms(roster, proof, bodies)
	if err != nil {
		return CloudMappingProviderDerivationBundle{}, err
	}
	objects := []interface{}{map[string]interface{}{"row_kind": "artifact_manifest", "artifact": "cloud_mapping_full_derivation", "artifact_version": "1", "canonical_admission_authorized": false, "independent_generic_reexecution_required": true}}
	for _, selection := range execution.FieldSelections {
		programRaw := selection.Program.Program
		var programObject map[string]interface{}
		if err := strictUnmarshal(programRaw, &programObject); err != nil {
			return CloudMappingProviderDerivationBundle{}, err
		}
		var program exactDocumentationDerivationProgram
		ref := dependencyProfileReference{id: selection.Program.ProfileID, version: selection.Program.ProfileVersion, digest: selection.Program.ProgramSHA256}
		program, err = parseExactDocumentationDerivationProgram(programRaw, ref)
		if err != nil {
			return CloudMappingProviderDerivationBundle{}, err
		}
		properties := map[string]interface{}{}
		for key, value := range program.OrderedRules[0].OutputFields {
			properties[key] = cloudMappingClosedSchema(value)
		}
		required := append([]string(nil), program.OrderedRules[0].ExactOutputFieldNames...)
		sort.Strings(required)
		schemaID := "urn:velenza:cloud-mapping:claim:" + strconv.Itoa(len(objects))
		schema, err := canonicalFactoryJSON(map[string]interface{}{"$schema": validationProfileDraft202012, "$id": schemaID, "type": "object", "additionalProperties": false, "required": required, "properties": properties})
		if err != nil {
			return CloudMappingProviderDerivationBundle{}, err
		}
		schemaRef := dependencyProfileReference{id: schemaID, version: "1", digest: sha256Hex(schema)}
		objects = append(objects, map[string]interface{}{"row_kind": "validation_schema", "validation_schema_id": schemaRef.id, "validation_schema_version": schemaRef.version, "validation_schema_sha256": schemaRef.digest, "claim_kind": "field_contract", "schema_dialect": validationProfileDraft202012, "canonical_schema_json": string(schema)}, map[string]interface{}{"row_kind": "derivation_profile", "derivation_profile_id": ref.id, "derivation_profile_version": ref.version, "derivation_profile_sha256": ref.digest, "claim_kind": "field_contract", "validation_schema_binding": map[string]interface{}{"validation_schema_id": schemaRef.id, "validation_schema_version": schemaRef.version, "validation_schema_sha256": schemaRef.digest}, "program": programObject})
	}
	objects = append(objects, map[string]interface{}{"row_kind": "validation_summary", "validation_schema_count": json.Number(strconv.Itoa(len(execution.FieldSelections))), "derivation_profile_count": json.Number(strconv.Itoa(len(execution.FieldSelections))), "classifier_profile_count": json.Number("0"), "dependency_resolution_profile_count": json.Number("0"), "canonical_admission_authorized": false, "independent_generic_reexecution_required": true, "result": "candidate_closed_source_neutral_derivation_profile"})
	var raw []byte
	for _, object := range objects {
		line, err := canonicalFactoryJSON(object)
		if err != nil {
			return CloudMappingProviderDerivationBundle{}, err
		}
		raw = append(raw, line...)
		raw = append(raw, '\n')
	}
	rows, err := parseDependencySemanticRows(artifactInput{Path: "cloud-mapping-full-profiles.jsonl", Raw: raw, SHA256: sha256Hex(raw), Structured: true})
	if err != nil {
		return CloudMappingProviderDerivationBundle{}, err
	}
	profiles, err := parseExecutableDocumentationDerivationProfiles(rows)
	if err != nil {
		return CloudMappingProviderDerivationBundle{}, err
	}
	profileExecution, err := executeDocumentationDerivationProfileSet(profiles, proof, bodies)
	if err != nil {
		return CloudMappingProviderDerivationBundle{}, err
	}
	if profileExecution.FactCount != int64(len(roster.Occurrences)) {
		return CloudMappingProviderDerivationBundle{}, fmt.Errorf("multi-profile field fact closure=%d want %d", profileExecution.FactCount, len(roster.Occurrences))
	}
	return CloudMappingProviderDerivationBundle{Execution: execution, ProfileRows: rows, Profiles: profiles, ProfileExecution: profileExecution}, nil
}

func cloudMappingClosedSchema(value interface{}) map[string]interface{} {
	schema := map[string]interface{}{}
	switch typed := value.(type) {
	case map[string]interface{}:
		properties := map[string]interface{}{}
		for key, child := range typed {
			properties[key] = cloudMappingClosedSchema(child)
		}
		schema["type"], schema["additionalProperties"], schema["properties"] = "object", false, properties
	case []interface{}:
		schema["type"] = "array"
		if len(typed) != 0 {
			items := make([]interface{}, len(typed))
			for i := range typed {
				items[i] = cloudMappingClosedSchema(typed[i])
			}
			schema["prefixItems"], schema["items"] = items, false
		}
	case json.Number:
		schema["type"] = "number"
	case string:
		schema["type"] = "string"
	case bool:
		schema["type"] = "boolean"
	}
	return schema
}

// CloudMappingFieldSelection exposes the exact selected range consumed by a
// generated field program so a source-package owner can form its sealed
// classification occurrence and derivation-profile materialization.
type CloudMappingFieldSelection struct {
	FieldSourceSymbol string
	ModelSourceID     string
	Locator           CloudCatalogEvidenceLocator
	Program           cloudMappingFieldProgram
}

// ExecuteCloudMappingProviderPrograms executes every exact generated field
// program in a single-provider roster against the existing selected-evidence
// executor. Each program retains its original byte-pinned profile and its
// own one-outcome source symbol; no program is merged or rewritten.
func ExecuteCloudMappingProviderPrograms(roster CloudMappingOccurrenceRoster, proof sourceClassificationSelectionProof, bodies map[string]exactEvidenceBody) (CloudMappingProviderExecution, error) {
	if err := ValidateCloudMappingOccurrenceRoster(roster, roster.Totals); err != nil {
		return CloudMappingProviderExecution{}, err
	}
	provider := roster.Occurrences[0].ProviderID
	facts := make([]exactDocumentationDerivedFact, 0, len(roster.Occurrences))
	fields := make([]CloudMappingFieldSelection, 0, len(roster.Occurrences))
	owners := map[string]CloudMappingSchemaOwnerSelection{}
	for _, occurrence := range roster.Occurrences {
		if occurrence.ProviderID != provider {
			return CloudMappingProviderExecution{}, fmt.Errorf("provider execution roster is mixed")
		}
		reference := dependencyProfileReference{id: occurrence.Program.ProfileID, version: occurrence.Program.ProfileVersion, digest: occurrence.Program.ProgramSHA256}
		program, err := parseExactDocumentationDerivationProgram(occurrence.Program.Program, reference)
		if err != nil {
			return CloudMappingProviderExecution{}, fmt.Errorf("field %q program: %w", occurrence.FieldSourceSymbol, err)
		}
		derived, err := executeExactDocumentationDerivationProgram(reference, program, proof, bodies)
		if err != nil || len(derived) != 1 {
			return CloudMappingProviderExecution{}, fmt.Errorf("field %q execution facts=%d: %w", occurrence.FieldSourceSymbol, len(derived), err)
		}
		facts = append(facts, derived[0])
		fields = append(fields, CloudMappingFieldSelection{FieldSourceSymbol: occurrence.FieldSourceSymbol, ModelSourceID: occurrence.ModelSourceID, Locator: occurrence.Program.Locator, Program: occurrence.Program})
		owner := CloudMappingSchemaOwnerSelection{SourceSchemaOwnerSymbol: occurrence.SourceSchemaOwnerSymbol, ModelSourceID: occurrence.ModelSourceID, Locator: occurrence.SourceSchemaOwnerLocator, SelectedRangeSHA256: occurrence.SourceSchemaOwnerRangeSHA256}
		if previous, exists := owners[owner.SourceSchemaOwnerSymbol]; exists {
			if previous.ModelSourceID != owner.ModelSourceID || previous.Locator != owner.Locator || previous.SelectedRangeSHA256 != owner.SelectedRangeSHA256 {
				return CloudMappingProviderExecution{}, fmt.Errorf("schema owner %q evidence changed", owner.SourceSchemaOwnerSymbol)
			}
		} else {
			owners[owner.SourceSchemaOwnerSymbol] = owner
		}
	}
	if len(facts) != len(roster.Occurrences) {
		return CloudMappingProviderExecution{}, fmt.Errorf("provider field execution closure is incomplete")
	}
	selections := make([]CloudMappingSchemaOwnerSelection, 0, len(owners))
	for _, selection := range owners {
		selections = append(selections, selection)
	}
	sort.Slice(facts, func(i, j int) bool { return facts[i].InputSourceSymbol < facts[j].InputSourceSymbol })
	sort.Slice(fields, func(i, j int) bool { return fields[i].FieldSourceSymbol < fields[j].FieldSourceSymbol })
	sort.Slice(selections, func(i, j int) bool {
		return selections[i].SourceSchemaOwnerSymbol < selections[j].SourceSchemaOwnerSymbol
	})
	return CloudMappingProviderExecution{ProviderID: provider, Roster: roster, FieldFacts: facts, SchemaOwnerSelections: selections, FieldSelections: fields}, nil
}

// MergeCloudMappingSourceContractProjection is the artifact-emission seam for
// the mapping-owned rows. base must contain the independently sealed source
// document/operation authority rows but no preexisting field contracts or
// endpoint-schema bindings. The function returns JSON-ready rows; callers
// still write them through their normal sealed source-package artifact path.
func MergeCloudMappingSourceContractProjection(base []map[string]interface{}, projection CloudMappingSourceContractProjection) ([]map[string]interface{}, error) {
	if len(projection.FieldContracts) == 0 || len(projection.ResourceSchemaBindings) == 0 {
		return nil, fmt.Errorf("mapping source-contract projection is incomplete")
	}
	result := make([]map[string]interface{}, 0, len(base)+len(projection.FieldContracts)+len(projection.ResourceSchemaBindings))
	manifestFound := false
	summaryFound := false
	for _, row := range base {
		kind, _ := row["row_kind"].(string)
		if kind == "field_contract" || kind == "api_resource_source_schema_binding" {
			return nil, fmt.Errorf("base source contract already carries mapping-owned row %q", kind)
		}
		copy := make(map[string]interface{}, len(row)+1)
		for key, value := range row {
			copy[key] = value
		}
		if kind == "artifact_manifest" {
			if manifestFound || copy["api_resource_source_schema_binding_contract"] != "v1" {
				return nil, fmt.Errorf("base source contract lacks v1 schema-binding manifest")
			}
			manifestFound = true
		}
		if kind == "validation_summary" {
			if summaryFound {
				return nil, fmt.Errorf("base source contract repeats validation summary")
			}
			summaryFound = true
			copy["field_contract_count"] = len(projection.FieldContracts)
		}
		result = append(result, copy)
	}
	if !manifestFound || !summaryFound {
		return nil, fmt.Errorf("base source contract lacks manifest or validation summary")
	}
	result = append(result, projection.FieldContracts...)
	result = append(result, projection.ResourceSchemaBindings...)
	return result, nil
}

// ComposeCloudMappingSourceContractProjection materializes every executed
// field fact and its endpoint/schema bridge. It is the production handoff
// seam for a full provider package; any missing, substituted, or duplicate
// fact fails before source-package serialization.
func ComposeCloudMappingSourceContractProjection(roster CloudMappingOccurrenceRoster, nativeByResource map[string]CloudMappingNativeResourceIdentity, facts []exactDocumentationDerivedFact) (CloudMappingSourceContractProjection, error) {
	if err := ValidateCloudMappingOccurrenceRoster(roster, roster.Totals); err != nil {
		return CloudMappingSourceContractProjection{}, err
	}
	bySymbol := map[string]exactDocumentationDerivedFact{}
	for _, fact := range facts {
		if fact.TargetArtifactRole != dependencySemanticRoleSourceContract || fact.TargetRowKind != "field_contract" || fact.TargetBindingKind != exactDocumentationTargetWholeRow || fact.InputSourceSymbol == "" {
			continue
		}
		if _, exists := bySymbol[fact.InputSourceSymbol]; exists {
			return CloudMappingSourceContractProjection{}, fmt.Errorf("executed field facts repeat source symbol %q", fact.InputSourceSymbol)
		}
		bySymbol[fact.InputSourceSymbol] = fact
	}
	rows := make([]map[string]interface{}, 0, len(roster.Occurrences))
	for _, occurrence := range roster.Occurrences {
		fact, ok := bySymbol[occurrence.FieldSourceSymbol]
		if !ok {
			return CloudMappingSourceContractProjection{}, fmt.Errorf("field source symbol %q has no executed fact", occurrence.FieldSourceSymbol)
		}
		if fact.Profile.id != occurrence.Program.ProfileID || fact.Profile.version != occurrence.Program.ProfileVersion || fact.Profile.digest != occurrence.Program.ProgramSHA256 {
			return CloudMappingSourceContractProjection{}, fmt.Errorf("field source symbol %q fact profile is not its exact generated program", occurrence.FieldSourceSymbol)
		}
		output, err := decodeExactDocumentationFactOutputFields(fact)
		if err != nil {
			return CloudMappingSourceContractProjection{}, err
		}
		if output["source_symbol"] != occurrence.FieldSourceSymbol {
			return CloudMappingSourceContractProjection{}, fmt.Errorf("field source symbol %q output binding drifted", occurrence.FieldSourceSymbol)
		}
		if len(fact.EvidenceLocator.SourceRefs) != 1 || len(fact.EvidenceLocator.SourceURLs) != 1 {
			return CloudMappingSourceContractProjection{}, fmt.Errorf("field source symbol %q has non-singular exact source coordinate", occurrence.FieldSourceSymbol)
		}
		row := make(map[string]interface{}, len(output)+8)
		for key, value := range output {
			row[key] = value
		}
		row["row_kind"] = "field_contract"
		row[exactDocumentationDerivedFactIDField] = fact.FactID
		row["source_symbol"] = occurrence.FieldSourceSymbol
		row["surface_kind"] = "resource"
		row["source_ref"] = fact.EvidenceLocator.SourceRefs[0]
		row["source_url"] = fact.EvidenceLocator.SourceURLs[0]
		row["source_content_sha256"] = fact.EvidenceLocator.SourceContentSHA256
		row["evidence_hydration_coordinate"] = map[string]interface{}{"source_content_sha256": fact.EvidenceLocator.SourceContentSHA256, "byte_start_offset": fact.EvidenceLocator.ByteStartOffset, "byte_end_offset_exclusive": fact.EvidenceLocator.ByteEndOffsetExclusive, "selected_range_byte_count": fact.EvidenceLocator.SelectedRangeByteCount, "selected_range_sha256": fact.EvidenceLocator.SelectedRangeSHA256}
		rows = append(rows, row)
	}
	bindings, err := BuildCloudMappingSourceContractSchemaBindings(roster, nativeByResource, facts)
	if err != nil {
		return CloudMappingSourceContractProjection{}, err
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i]["source_symbol"].(string) < rows[j]["source_symbol"].(string) })
	return CloudMappingSourceContractProjection{FieldContracts: rows, ResourceSchemaBindings: bindings}, nil
}

// BuildCloudMappingSourceContractSchemaBindings emits the complete v1
// api_resource_source_schema_binding rows after (and only after) the exact
// field recipes have executed. It binds every emitted field fact to its real
// endpoint and declared-schema evidence surface. It deliberately does not
// execute recipes, classify source evidence, or create graph identities.
func BuildCloudMappingSourceContractSchemaBindings(roster CloudMappingOccurrenceRoster, nativeByResource map[string]CloudMappingNativeResourceIdentity, facts []exactDocumentationDerivedFact) ([]map[string]interface{}, error) {
	groups, err := BuildCloudMappingResourceFieldGroups(roster)
	if err != nil {
		return nil, err
	}
	if len(nativeByResource) != len(groups) {
		return nil, fmt.Errorf("native API-resource identity roster is not exact")
	}
	bySymbol := map[string]exactDocumentationDerivedFact{}
	for _, fact := range facts {
		if fact.TargetArtifactRole != dependencySemanticRoleSourceContract || fact.TargetRowKind != "field_contract" || fact.TargetBindingKind != exactDocumentationTargetWholeRow || fact.InputSourceSymbol == "" {
			continue
		}
		if _, duplicate := bySymbol[fact.InputSourceSymbol]; duplicate {
			return nil, fmt.Errorf("executed field facts repeat source symbol %q", fact.InputSourceSymbol)
		}
		bySymbol[fact.InputSourceSymbol] = fact
	}
	rows := make([]map[string]interface{}, 0, len(groups))
	usedFacts := map[string]struct{}{}
	usedNativeIDs := map[string]struct{}{}
	for _, group := range groups {
		native, ok := nativeByResource[group.Resource.ResourceKey]
		if !ok || native.APIResourceID == "" || native.APIResourceSourceSymbol == "" {
			return nil, fmt.Errorf("resource %q has no sealed native identity", group.Resource.ResourceKey)
		}
		if _, duplicate := usedNativeIDs[native.APIResourceID]; duplicate {
			return nil, fmt.Errorf("native API-resource ID %q repeats", native.APIResourceID)
		}
		usedNativeIDs[native.APIResourceID] = struct{}{}
		row := map[string]interface{}{"row_kind": "api_resource_source_schema_binding", "api_resource_id": native.APIResourceID, "api_resource_source_symbol": native.APIResourceSourceSymbol}
		if len(group.SchemaSurfaces) == 0 {
			row["binding_status"] = "no_source_schema_surface"
			rows = append(rows, row)
			continue
		}
		surfaces := make([]interface{}, 0, len(group.SchemaSurfaces))
		for _, surface := range group.SchemaSurfaces {
			if surface.SourceSchemaOwnerSymbol == "" || len(surface.FieldSourceSymbols) == 0 {
				return nil, fmt.Errorf("resource %q has incomplete schema surface", group.Resource.ResourceKey)
			}
			identities := make([]string, 0, len(surface.Occurrences))
			for _, occurrence := range surface.Occurrences {
				fact, ok := bySymbol[occurrence.FieldSourceSymbol]
				if !ok {
					return nil, fmt.Errorf("field source symbol %q has no executed fact", occurrence.FieldSourceSymbol)
				}
				if fact.Profile.id != occurrence.Program.ProfileID || fact.Profile.version != occurrence.Program.ProfileVersion || fact.Profile.digest != occurrence.Program.ProgramSHA256 {
					return nil, fmt.Errorf("field source symbol %q fact profile is not its exact generated program", occurrence.FieldSourceSymbol)
				}
				output, err := decodeExactDocumentationFactOutputFields(fact)
				if err != nil {
					return nil, err
				}
				identityRow := make(map[string]interface{}, len(output)+3)
				for key, value := range output {
					identityRow[key] = value
				}
				identityRow[exactDocumentationDerivedFactIDField] = fact.FactID
				identityRow["source_symbol"] = occurrence.FieldSourceSymbol
				identityRow["surface_kind"] = "resource"
				identity, err := sourceFieldOccurrenceIdentity(identityRow)
				if err != nil {
					return nil, fmt.Errorf("field source symbol %q occurrence identity: %w", occurrence.FieldSourceSymbol, err)
				}
				if _, duplicate := usedFacts[identity]; duplicate {
					return nil, fmt.Errorf("field occurrence identity %q repeats", identity)
				}
				usedFacts[identity] = struct{}{}
				identities = append(identities, identity)
			}
			sort.Strings(identities)
			fields := append([]string(nil), surface.FieldSourceSymbols...)
			sort.Strings(fields)
			ownerLocatorID := native.SchemaOwnerEvidenceLocatorIDs[surface.SourceSchemaOwnerSymbol]
			if ownerLocatorID == "" {
				return nil, fmt.Errorf("schema owner %q has no sealed owner evidence locator", surface.SourceSchemaOwnerSymbol)
			}
			surfaces = append(surfaces, map[string]interface{}{"source_schema_owner_symbol": surface.SourceSchemaOwnerSymbol, "source_schema_owner_evidence_locator_id": ownerLocatorID, "field_source_symbols": fields, "field_contract_occurrence_identities": identities})
		}
		row["binding_status"] = "field_surface_present"
		row["source_schema_surfaces"] = surfaces
		rows = append(rows, row)
	}
	if len(usedFacts) != len(roster.Occurrences) || len(bySymbol) != len(roster.Occurrences) {
		return nil, fmt.Errorf("executed field fact roster does not close every mapping occurrence")
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i]["api_resource_id"].(string) < rows[j]["api_resource_id"].(string) })
	return rows, nil
}
